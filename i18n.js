let currentLanguage = 'hu';
try {
    if (localStorage.getItem('forgestudio-language') === 'en') currentLanguage = 'en';
} catch (error) {
    console.warn('Language preference could not be read:', error);
}

function translate(text) {
    return currentLanguage === 'en' ? (englishText[text] || text) : text;
}

function bilingual(hu, en) {
    return currentLanguage === 'en' ? en : hu;
}

const originalText = new WeakMap();
const originalAttributes = new WeakMap();
function localizeTree(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        if (!originalText.has(node)) originalText.set(node, node.nodeValue);
        const original = originalText.get(node);
        const trimmed = original.trim();
        if (trimmed) node.nodeValue = original.replace(trimmed, translate(trimmed));
    }
    const elements = root.querySelectorAll('[placeholder], [aria-label]');
    elements.forEach((element) => {
        if (!originalAttributes.has(element)) {
            originalAttributes.set(element, {
                placeholder: element.getAttribute('placeholder'),
                label: element.getAttribute('aria-label')
            });
        }
        const original = originalAttributes.get(element);
        if (original.placeholder !== null) element.setAttribute('placeholder', translate(original.placeholder));
        if (original.label !== null) element.setAttribute('aria-label', translate(original.label));
    });
}

const languageSelect = document.querySelector('#language-select');
function applyLanguage() {
    document.documentElement.lang = currentLanguage;
    document.title = translate('ForgeStudio – Gépajánló');
    document.querySelector('meta[name="description"]').content = translate('Találd meg a játékokhoz vagy fejlesztéshez illő gépet.');
    languageSelect.value = currentLanguage;
    localizeTree(document.body);
    window.dispatchEvent(new Event('forgestudio-language-change'));
}

languageSelect.addEventListener('change', () => {
    currentLanguage = languageSelect.value;
    try {
        localStorage.setItem('forgestudio-language', currentLanguage);
    } catch (error) {
        console.warn('Language preference could not be saved:', error);
    }
    applyLanguage();
});
applyLanguage();

